"""Convert the two supplied images into source and compiled-program icons.

Run once with the source PNG paths; subsequent builds use assets/*.png.
The PE resource tree is position independent except for the RVA fields fixed
by pe_writer.h. A copy of the user's originals is retained in assets/.
"""
from pathlib import Path
from PIL import Image, ImageOps
import shutil
import struct
import sys

root = Path(__file__).resolve().parent.parent
assets = root / 'assets'
assets.mkdir(exist_ok=True)
for name, supplied in zip(['source', 'compiled'], sys.argv[1:3]):
    shutil.copyfile(supplied, assets / f'{name}-original.png')
for name in ['source', 'compiled']:
    image = Image.open(assets / f'{name}-original.png').convert('RGBA')
    image = ImageOps.pad(image, (256, 256), color=(255, 255, 255, 255))
    image.save(assets / f'{name}.png')
    image.save(assets / f'{name}.ico', sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
icons = root / 'vscode-assisscript' / 'icons'
icons.mkdir(exist_ok=True)
for name in ['source', 'compiled']:
    shutil.copyfile(assets / f'{name}.png', icons / f'{name}.png')

ico = (assets / 'compiled.ico').read_bytes()
count = struct.unpack_from('<H', ico, 4)[0]
entries = [struct.unpack_from('<BBBBHHII', ico, 6 + 16*i) for i in range(count)]
# Root -> resource type -> name -> neutral language -> data descriptor.
rsrc = bytearray(16 + 2*8)
patches = []
def directory(ids):
    offset = len(rsrc)
    rsrc.extend(struct.pack('<IIHHHH', 0, 0, 0, 0, 0, len(ids)))
    for ident in ids:
        rsrc.extend(struct.pack('<II', ident, 0))
    return offset
def put32(at, value):
    struct.pack_into('<I', rsrc, at, value)
put32(12, 2 << 16)
for type_index, (kind, ids) in enumerate([(3, list(range(1, count+1))), (14, [1])]):
    type_offset = directory(ids)
    put32(16 + type_index*8, kind)
    put32(20 + type_index*8, type_offset | 0x80000000)
    for index, ident in enumerate(ids):
        lang = directory([0])
        put32(type_offset + 20 + index*8, lang | 0x80000000)
        descriptor = len(rsrc)
        rsrc.extend(bytes(16))
        put32(lang + 20, descriptor)
        if kind == 3:
            entry = entries[ident-1]
            payload = ico[entry[7]:entry[7]+entry[6]]
        else:
            payload = struct.pack('<HHH', 0, 1, count)
            payload += b''.join(struct.pack('<BBBBHHIH', *entry[:7], i+1) for i, entry in enumerate(entries))
        while len(rsrc) % 4:
            rsrc.append(0)
        put32(descriptor, len(rsrc))
        patches.append(descriptor)
        put32(descriptor+4, len(payload))
        rsrc.extend(payload)
lines = ['/* Generated by tools/build-icons.py from the supplied compiled icon. */', 'static const unsigned char icon_resource[] = {']
lines += [','.join(map(str, rsrc[i:i+24])) + ',' for i in range(0, len(rsrc), 24)]
lines += ['};', 'static const size_t icon_rva_patches[] = {' + ','.join(map(str, patches)) + '};']
(root / 'src' / 'icon_blob.h').write_text('\n'.join(lines)+'\n', encoding='utf-8')
print(f'Ícones criados: {count} resoluções; recursos PE com {len(rsrc)} bytes.')
