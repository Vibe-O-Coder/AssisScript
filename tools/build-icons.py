"""Rebuild the user-selected v1 icons from the checked-in original SVGs.
Requires Pillow and CairoSVG only on the maintainer's machine.
"""
from pathlib import Path
from PIL import Image
from io import BytesIO
import cairosvg
import shutil
import struct
import hashlib
import json
root = Path(__file__).resolve().parent.parent
assets = root / 'assets'
icons = root / 'vscode-assisscript' / 'icons'
icons.mkdir(exist_ok=True)
for name in ['source', 'compiled']:
    svg = assets / 'propostas' / f'{name}-v1.svg'
    png = cairosvg.svg2png(url=str(svg),output_width=1024,output_height=1024)
    master = Image.open(BytesIO(png)).convert('RGBA')
    image = master.resize((256,256),Image.Resampling.LANCZOS)
    image.save(assets / f'{name}.png')
    image.save(assets / f'{name}.ico',sizes=[(16,16),(24,24),(32,32),(48,48),(64,64),(128,128),(256,256)])
    master.save(assets / f'{name}.icns')
    shutil.copyfile(assets / f'{name}.png',icons / f'{name}.png')

ico = (assets / 'compiled.ico').read_bytes()
count = struct.unpack_from('<H', ico, 4)[0]
entries = [struct.unpack_from('<BBBBHHII', ico, 6 + 16*i) for i in range(count)]
# Root -> resource type -> name -> neutral language -> data descriptor.
rsrc = bytearray(16 + 2*8)
patches = []
def directory(ids):
    offset = len(rsrc)
    rsrc.extend(struct.pack('<IIHHHH', 0, 0, 0, 0, 0, len(ids)))
    for ident in ids:
        rsrc.extend(struct.pack('<II', ident, 0))
    return offset
def put32(at, value):
    struct.pack_into('<I', rsrc, at, value)
put32(12, 2 << 16)
for type_index, (kind, ids) in enumerate([(3, list(range(1, count+1))), (14, [1])]):
    type_offset = directory(ids)
    put32(16 + type_index*8, kind)
    put32(20 + type_index*8, type_offset | 0x80000000)
    for index, ident in enumerate(ids):
        lang = directory([0])
        put32(type_offset + 20 + index*8, lang | 0x80000000)
        descriptor = len(rsrc)
        rsrc.extend(bytes(16))
        put32(lang + 20, descriptor)
        if kind == 3:
            entry = entries[ident-1]
            payload = ico[entry[7]:entry[7]+entry[6]]
        else:
            payload = struct.pack('<HHH', 0, 1, count)
            payload += b''.join(struct.pack('<BBBBHHIH', *entry[:7], i+1) for i, entry in enumerate(entries))
        while len(rsrc) % 4:
            rsrc.append(0)
        put32(descriptor, len(rsrc))
        patches.append(descriptor)
        put32(descriptor+4, len(payload))
        rsrc.extend(payload)
lines = ['/* Generated by tools/build-icons.py from assets/propostas/compiled-v1.svg. */', 'static const unsigned char icon_resource[] = {']
lines += [','.join(map(str, rsrc[i:i+24])) + ',' for i in range(0, len(rsrc), 24)]
lines += ['};', 'static const size_t icon_rva_patches[] = {' + ','.join(map(str, patches)) + '};']
(root / 'src' / 'icon_blob.h').write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
icns=(assets/'compiled.icns').read_bytes()
(root/'src/icon_icns.h').write_text('/* Generated from compiled-v1.svg by tools/build-icons.py. */\nstatic const unsigned char compiled_icns[] = {\n'+''.join(','.join(map(str,icns[i:i+24]))+',\n' for i in range(0,len(icns),24))+'};\n',encoding='utf-8',newline='\n')
tracked=['tools/build-icons.py','src/icon_blob.h','src/icon_icns.h','assets/compiler.rc','assets/installer.rc']
tracked += [f'assets/propostas/{name}-v1.svg' for name in ('source','compiled')]
tracked += [f'assets/{name}.{ext}' for name in ('source','compiled') for ext in ('png','ico','icns')]
tracked += [f'vscode-assisscript/icons/{name}.png' for name in ('source','compiled')]
(assets/'IDENTIDADE-V1.json').write_text(json.dumps(dict(selected='v1',origin='Project-owned geometric SVG sources selected by the owner on 2026-10-29; no tracing or incorporation of the retired stickers.',files={name:hashlib.sha256((root/name).read_bytes()).hexdigest() for name in tracked}),indent=2)+'\n',encoding='utf-8',newline='\n')
print(f'Ícones criados: {count} resoluções; recursos PE com {len(rsrc)} bytes.')
