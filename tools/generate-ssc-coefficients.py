start=source.index('// BEGIN SSC COEFFICIENTS')+len('// BEGIN SSC COEFFICIENTS\n')
end=source.index('// END SSC COEFFICIENTS')
updated=source[:start]+text+source[end:]
corpus=ROOT/'tests/fixtures/ssc-coefficients.json'
