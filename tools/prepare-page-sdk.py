"""Embed the pinned page SDK for compilation without filesystem authority."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
data = (ROOT / 'stdlib/page.assis').read_text(encoding='utf-8')
content = '/* Generated by tools/prepare-page-sdk.py; do not edit. */\n' + ''.join(
    json.dumps(line, ensure_ascii=True) + '\n' for line in data.splitlines(keepends=True))
path = ROOT / 'src/page_sdk.inc'
if args.check:
    if path.read_text(encoding='utf-8') != content:
        raise SystemExit('Embedded page SDK is stale')
else:
    path.write_text(content, encoding='utf-8', newline='\n')
