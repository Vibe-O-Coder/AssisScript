"""Build freestanding, relocation-free AArch64 runtime blobs with LLVM tools.

Only a maintainer needs clang/lld/objcopy/nm. Installed assis emits bytes itself.
"""
from pathlib import Path
import subprocess
import re
import shutil
ROOT=Path(__file__).resolve().parent.parent
BUILD=ROOT/'build/arm64-runtime';BUILD.mkdir(parents=True,exist_ok=True)
def run(*args):return subprocess.check_output(list(map(str,args)),text=True)
for platform,macro in [('linux','ART'),('macos','AMRT')]:
    obj=BUILD/(platform+'.o');elf=BUILD/(platform+'.elf');binary=BUILD/(platform+'.bin')
    flags=['--target=aarch64-none-elf','-Oz','-ffreestanding','-fno-builtin','-fno-stack-protector','-fno-unwind-tables','-fno-asynchronous-unwind-tables','-fno-jump-tables','-mno-outline-atomics','-ffixed-x18','-fPIC']
    run(shutil.which('clang-18') or 'clang',*flags,*(['-DARM_MACOS'] if platform=='macos' else []),'-c',ROOT/'src/runtime_arm64.c','-o',obj)
    objects=[obj]
    if platform=='macos':
        asm=BUILD/'imports.S';stub=BUILD/'imports.o'
        imports=['read','write','close','fsync','mmap','munmap','nanosleep','clock_gettime','rename','unlink','open','_exit','__error']
        asm.write_text('.text\n'+''.join(f'.global os_{name}\nos_{name}:\nadr x16, arm_import_{name}\nldr x17, [x16]\nadd x16,x16,x17\nldr x16,[x16]\nbr x16\n.balign 8\n.global arm_import_{name}\narm_import_{name}: .quad 0\n' for name in imports),encoding='utf-8')
        content=asm.read_text().replace('os_open:\nadr x16', 'os_open:\nsub sp,sp,#32\nstp x29,x30,[sp,#16]\nstr x2,[sp]\nadr x16').replace('br x16\n.balign 8\n.global arm_import_open', 'blr x16\nldp x29,x30,[sp,#16]\nadd sp,sp,#32\nret\n.balign 8\n.global arm_import_open')
        asm.write_text(content,encoding='utf-8')
        run(shutil.which('clang-18') or 'clang','--target=aarch64-none-elf','-c',asm,'-o',stub);objects.append(stub)
    script=BUILD/'blob.ld';script.write_text('SECTIONS { . = 0; .text : { *(.text*) *(.rodata*) *(.data.rel.ro*) } /DISCARD/ : { *(.comment*) *(.note*) *(.eh_frame*) } }',encoding='utf-8')
    for item in objects:
        relocations=run('aarch64-linux-gnu-readelf','-r',item)
        assert not re.search(r'R_AARCH64_ABS(?:16|32|64)\b',relocations),('Non-PIC data address',relocations)
    run(shutil.which('ld.lld-18') or 'ld.lld','-T',script,'--no-undefined','--entry=ar_init',*objects,'-o',elf)
    assert 'There are no relocations' in run('aarch64-linux-gnu-readelf','-r',elf)
    sections=run('aarch64-linux-gnu-size','-A',elf)
    assert not re.search(r'\.(?:bss|data)\s+[1-9]',sections),sections
    run('aarch64-linux-gnu-objcopy','-O','binary','--only-section=.text',elf,binary)
    blob=binary.read_bytes();names=[];patches=[]
    for line in run('aarch64-linux-gnu-nm','-n',elf).splitlines():
        fields=line.split()
        if len(fields)!=3:continue
        if fields[1]=='T' and fields[2].startswith('ar_'):names.append((fields[2][3:],int(fields[0],16)))
        if fields[2].startswith('arm_import_'):patches.append((fields[2][11:],int(fields[0],16)))
    name='runtime_arm64_'+platform
    lines=[f'/* Generated by tools/embed-arm64.py from runtime_arm64.c ({platform}). */',f'static const unsigned char {name}[] = {{']
    lines += [','.join(map(str,blob[i:i+24]))+',' for i in range(0,len(blob),24)]
    lines += ['};']+[f'#define {macro}_{n} 0x{at:x}' for n,at in names]
    if platform=='macos':lines+=['static const struct { size_t offset; const char *name; } arm_macos_import_patches[] = {']+[f'{{0x{at:x},"{n}"}},' for n,at in patches]+['};']
    (ROOT/'src'/f'{name}.h').write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    print(platform,len(blob),'bytes,',len(names),'entrypoints')
